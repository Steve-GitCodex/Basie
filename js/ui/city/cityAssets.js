/**
 * cityAssets.js
 * Sprite manifest + image loader for the iso city view.
 *
 * Building sprites: rig-rendered grit set + AI-generated set (ADR 0021/0024).
 * Each building sprite includes its own ground block and is drawn bottom-anchored
 * over the procedural city ground (`js/ui/city/cityGround.js`).
 */

